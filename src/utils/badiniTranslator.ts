// Sort once from longest to shortest target word to avoid partial matching bugs
const SORTED_REPLACEMENTS = [...BADINI_REPLACEMENTS].sort((a, b) => b[0].length - a[0].length);

export function cleanKurdishToBadini(text: string | undefined | null): string {
  if (!text) return '';
  let cleaned = text;
  
  for (const [target, replacement] of SORTED_REPLACEMENTS) {
    if (!cleaned.includes(target)) continue;
    // We use a global join/split or regex mapping for exact word replacements where boundary is respected,
    // but in Kurdish script word-boundaries can sometimes join or overlap with other letters or prefixes.
    // So simple replaceAll is ideal given the longest-to-shortest ordering guarantees correctness.
    cleaned = cleaned.split(target).join(replacement);
  }
  
  return cleaned;
}

// Helper to clean object fields dynamically
export function cleanObjectToBadini<T extends object>(obj: T, fieldsToClean: (keyof T)[]): T {
  if (!obj) return obj;
  const newObj = { ...obj };
  for (const field of fieldsToClean) {
    const val = newObj[field];
    if (typeof val === 'string') {
      newObj[field] = cleanKurdishToBadini(val) as any;
    } else if (Array.isArray(val)) {
      newObj[field] = val.map(item => {
        if (typeof item === 'string') {
          return cleanKurdishToBadini(item);
        } else if (item && typeof item === 'object') {
          return cleanObjectToBadini(item, Object.keys(item) as any);
        }
        return item;
      }) as any;
    }
  }
  return newObj;
}
